document.addEventListener("DOMContentLoaded", function () {
  var canvas = document.getElementById("lab-chart");
  var downloadButton = document.getElementById("lab-download");

  var planets = [
    { name: "Kepler-22b", mass: 2.4, radius: 2.4, distance: 600 },
    { name: "TRAPPIST-1e", mass: 0.8, radius: 0.9, distance: 39 },
    { name: "HD 209458 b", mass: 0.7, radius: 1.4, distance: 159 },
    { name: "K2-18b", mass: 8.6, radius: 2.6, distance: 124 },
  ];

  // Draw the planet mass chart
  function drawChart() {
    if (!canvas) return;

    var ctx = canvas.getContext("2d");
    var width = canvas.clientWidth;
    var height = 145;
    var pixelRatio = window.devicePixelRatio || 1;

    canvas.width = width * pixelRatio;
    canvas.height = height * pixelRatio;
    ctx.scale(pixelRatio, pixelRatio);

    ctx.clearRect(0, 0, width, height);

    var left = 28;
    var right = 12;
    var top = 12;
    var bottom = 28;
    var chartWidth = width - left - right;
    var chartHeight = height - top - bottom;
    var maxMass = 10;

    // Horizontal grid lines and labels
    ctx.font = "10px Arial";
    ctx.fillStyle = "#9bb1c9";
    ctx.strokeStyle = "#183149";
    ctx.lineWidth = 1;

    for (var i = 0; i <= 10; i += 5) {
      var y = top + chartHeight - (i / maxMass) * chartHeight;

      ctx.beginPath();
      ctx.moveTo(left, y);
      ctx.lineTo(width - right, y);
      ctx.stroke();

      ctx.fillText(i, 5, y + 4);
    }

    // Bars
    var gap = 12;
    var barWidth = (chartWidth - gap * 5) / planets.length;

    for (var j = 0; j < planets.length; j++) {
      var barHeight = (planets[j].mass / maxMass) * chartHeight;
      var x = left + gap + j * (barWidth + gap);
      var y = top + chartHeight - barHeight;

      ctx.fillStyle = "#00cbe8";
      ctx.fillRect(x, y, barWidth, barHeight);

      ctx.fillStyle = "#e3efff";
      ctx.textAlign = "center";
      ctx.fillText(planets[j].mass, x + barWidth / 2, y - 5);

      ctx.fillStyle = "#9bb1c9";
      var label = planets[j].name.split("-")[0];

      ctx.fillText(label, x + barWidth / 2, height - 8);
    }

    ctx.textAlign = "left";
  }

  // Download the sample data as a CSV file

  if (downloadButton) {
    downloadButton.addEventListener("click", function () {
      if (!window.jspdf) {
        alert(
          "PDF library could not load. Please check your internet connection.",
        );
        return;
      }

      var pdf = new window.jspdf.jsPDF();

      pdf.setFontSize(20);
      pdf.setTextColor(0, 150, 200);
      pdf.text("COSMOS - Space Data Lab", 20, 20);

      pdf.setFontSize(12);
      pdf.setTextColor(50, 50, 50);
      pdf.text("Sample Exoplanet Dataset", 20, 32);
      pdf.text("Mass and radius are sample values.", 20, 42);

      var startY = 58;
      var columns = ["Planet", "Mass", "Radius", "Distance (ly)"];
      var columnX = [20, 85, 115, 150];

      pdf.setFontSize(11);
      pdf.setTextColor(0, 120, 160);

      for (var i = 0; i < columns.length; i++) {
        pdf.text(columns[i], columnX[i], startY);
      }

      pdf.setDrawColor(0, 180, 210);
      pdf.line(20, startY + 4, 190, startY + 4);

      pdf.setFontSize(10);
      pdf.setTextColor(40, 40, 40);

      for (var j = 0; j < planets.length; j++) {
        var y = startY + 15 + j * 12;

        pdf.text(planets[j].name, columnX[0], y);
        pdf.text(String(planets[j].mass), columnX[1], y);
        pdf.text(String(planets[j].radius), columnX[2], y);
        pdf.text(String(planets[j].distance), columnX[3], y);
      }

      pdf.setFontSize(9);
      pdf.text("Generated by COSMOS Space Data Lab", 20, 120);

      pdf.save("cosmos-space-data.pdf");
    });
  }

  drawChart();

  // Redraw the chart when the window size changes
  window.addEventListener("resize", drawChart);
});
